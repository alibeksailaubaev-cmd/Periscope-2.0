/**
 * Импорт акта мойки ЗПП из мобильного приложения.
 * Excel в браузере → вкладка «Автоматизация» → Новый скрипт → вставить этот код
 * → Сохранить как «Импорт акта мойки».
 *
 * Порядок работы:
 *   1. В приложении нажать «Скопировать пакет».
 *   2. В книге открыть лист «Импорт», встать на A1, вставить (Ctrl+V).
 *   3. Автоматизация → Импорт акта мойки → Выполнить.
 *
 * Скрипт сам:
 *   • ставит 10 баллов всем позициям акта и очищает старые несоответствия;
 *   • проставляет баллы, описания, ответственных и отметку МДС из пакета;
 *   • пишет дату проверки, хронометраж и итоговый балл в «Динамику»;
 *   • дописывает несоответствия в «Архив несоответствий».
 * Лист «Журнал несоответствий» заполняется сам — там уже стоят формулы.
 */

const ЛИСТ_АКТ = "Акт мойки";
const ЛИСТ_ХРОНО = "Хронометраж";
const ЛИСТ_ДИНАМИКА = "Динамика";
const ЛИСТ_АРХИВ = "Архив несоответствий";
const ЛИСТ_ИМПОРТ = "Импорт";
const ПЕРВАЯ_СТРОКА = 9;    // первая позиция акта
const ПОСЛЕДНЯЯ_СТРОКА = 151; // последняя позиция акта

interface Исключение {
  r: number;   // номер строки на листе «Акт мойки»
  б: number;   // балл
  о?: string;  // описание несоответствия
  отв?: string; // ответственный за устранение
  срок?: string; // срок устранения (ГГГГ-ММ-ДД)
  мдс?: number; // 1 — обнаружены остатки МДС
  у?: string;  // участок
  н?: string;  // наименование оборудования/места
}
interface Пакет {
  v: number; акт: string; дата: string; врач: string; место: string;
  начало: string; окончание: string; балл: number; иск: Исключение[];
}

function main(workbook: ExcelScript.Workbook) {
  // ---------- 1. Читаем пакет с листа «Импорт» ----------
  let импорт = workbook.getWorksheet(ЛИСТ_ИМПОРТ);
  if (!импорт) {
    импорт = workbook.addWorksheet(ЛИСТ_ИМПОРТ);
    импорт.getRange("A1").setValue("");
    throw new Error("Создан лист «Импорт». Вставьте пакет из приложения в ячейку A1 и запустите скрипт снова.");
  }
  const сырой = String(импорт.getRange("A1").getValue() || "").trim();
  if (!сырой) throw new Error("Ячейка A1 листа «Импорт» пуста — вставьте пакет из приложения.");

  const пакет: Пакет = JSON.parse(сырой) as Пакет;
  const исключения = пакет.иск || [];
  const серийнаяДата = вДатуExcel(пакет.дата);

  // ---------- 2. Лист «Акт мойки» ----------
  const акт = workbook.getWorksheet(ЛИСТ_АКТ);
  акт.getRange("C4").setValue(серийнаяДата);

  // строки позиций = те, где в колонке A стоит номер, а в колонке B — наименование.
  // Проверка по B обязательна: строка 53 (заголовок «ВКО») тоже содержит число в A,
  // но объединена в диапазон A53:D53 — запись в неё вызвала бы ошибку.
  const шапка = акт.getRange(`A${ПЕРВАЯ_СТРОКА}:B${ПОСЛЕДНЯЯ_СТРОКА}`).getValues();
  const позиции: number[] = [];
  for (let i = 0; i < шапка.length; i++) {
    const номер = шапка[i][0];
    const наименование = шапка[i][1];
    if (typeof номер === "number" && typeof наименование === "string" && наименование !== "") {
      позиции.push(ПЕРВАЯ_СТРОКА + i);
    }
  }
  if (позиции.length === 0) throw new Error("На листе «Акт мойки» не найдено ни одной позиции.");

  // карта исключений по номеру строки
  const карта: { [строка: number]: Исключение } = {};
  for (const и of исключения) карта[и.r] = и;

  // пишем непрерывными блоками, чтобы не задеть объединённые строки-заголовки
  for (const блок of блоки(позиции)) {
    const мдс: string[][] = [];
    const баллы: number[][] = [];
    const описания: string[][] = [];
    const ответственные: string[][] = [];
    for (let строка = блок[0]; строка <= блок[1]; строка++) {
      const и = карта[строка];
      мдс.push([и && и.мдс ? "да" : ""]);
      баллы.push([и ? и.б : 10]);
      описания.push([и && и.о ? и.о : ""]);
      ответственные.push([и && и.отв ? и.отв : ""]);
    }
    const адрес = (кол: string) => `${кол}${блок[0]}:${кол}${блок[1]}`;
    акт.getRange(адрес("C")).setValues(мдс);
    акт.getRange(адрес("D")).setValues(баллы);
    акт.getRange(адрес("F")).setValues(описания);
    акт.getRange(адрес("G")).setValues(ответственные);
  }

  // ---------- 3. Лист «Хронометраж» ----------
  const хроно = workbook.getWorksheet(ЛИСТ_ХРОНО);
  const строкаХроно = найтиИлиДобавить(хроно, серийнаяДата, 2);
  хроно.getRange(`B${строкаХроно}`).setValue("ЗПП");
  if (пакет.начало) хроно.getRange(`C${строкаХроно}`).setValue(вДолюСуток(пакет.начало));
  if (пакет.окончание) хроно.getRange(`F${строкаХроно}`).setValue(вДолюСуток(пакет.окончание));
  хроно.getRange(`J${строкаХроно}`).setValue(пакет.врач);

  // ---------- 4. Лист «Динамика» ----------
  const динамика = workbook.getWorksheet(ЛИСТ_ДИНАМИКА);
  const строкаДин = найтиИлиДобавить(динамика, серийнаяДата, 2);
  динамика.getRange(`B${строкаДин}`).setValue("ЗПП");
  динамика.getRange(`C${строкаДин}`).setValue(пакет.балл);

  // ---------- 5. Лист «Архив несоответствий» ----------
  const несоответствия = исключения.filter(и => и.б < 10);
  if (несоответствия.length > 0) {
    const архив = workbook.getWorksheet(ЛИСТ_АРХИВ);
    const перваяСвободная = перваяПустая(архив, 4);
    const строки = несоответствия.map(и => [
      серийнаяДата,
      и.у || "",
      и.н || "",
      и.о || "",
      и.б,
      и.отв || "",
      и.срок ? вДатуExcel(и.срок) : "",
      "Открыто",
      ""
    ]);
    архив.getRange(`A${перваяСвободная}:I${перваяСвободная + строки.length - 1}`).setValues(строки);
  }

  // ---------- 6. Очищаем буфер ----------
  импорт.getRange("A1").clear(ExcelScript.ClearApplyTo.contents);
  console.log(
    `Акт ${пакет.акт} загружен: 131 позиция, несоответствий ${несоответствия.length}, итоговый балл ${пакет.балл}.`
  );
}

/** непрерывные диапазоны строк: [[9,52],[54,58],...] */
function блоки(строки: number[]): number[][] {
  const результат: number[][] = [];
  let начало = строки[0], предыдущая = строки[0];
  for (let i = 1; i < строки.length; i++) {
    if (строки[i] !== предыдущая + 1) {
      результат.push([начало, предыдущая]);
      начало = строки[i];
    }
    предыдущая = строки[i];
  }
  результат.push([начало, предыдущая]);
  return результат;
}

/** ищет дату в колонке A, при отсутствии — добавляет строку после последней заполненной */
function найтиИлиДобавить(лист: ExcelScript.Worksheet, дата: number, перваяСтрока: number): number {
  const колонка = лист.getRange(`A${перваяСтрока}:A${перваяСтрока + 999}`).getValues();
  let последняя = перваяСтрока - 1;
  for (let i = 0; i < колонка.length; i++) {
    const значение = колонка[i][0];
    if (значение === "" || значение === null) continue;
    последняя = перваяСтрока + i;
    if (typeof значение === "number" && Math.floor(значение) === дата) return последняя;
  }
  const новая = последняя + 1;
  лист.getRange(`A${новая}`).setValue(дата);
  return новая;
}

/** первая пустая строка по колонке A */
function перваяПустая(лист: ExcelScript.Worksheet, перваяСтрока: number): number {
  const колонка = лист.getRange(`A${перваяСтрока}:A${перваяСтрока + 4999}`).getValues();
  for (let i = колонка.length - 1; i >= 0; i--) {
    const значение = колонка[i][0];
    if (значение !== "" && значение !== null) return перваяСтрока + i + 1;
  }
  return перваяСтрока;
}

/** «2026-08-20» → серийный номер даты Excel */
function вДатуExcel(iso: string): number {
  const части = iso.split("-").map(ч => parseInt(ч, 10));
  const utc = Date.UTC(части[0], части[1] - 1, части[2]);
  return Math.round(utc / 86400000) + 25569;
}

/** «07:45:30» → доля суток (формат ч:мм в книге отобразит как время) */
function вДолюСуток(время: string): number {
  const ч = время.split(":").map(x => parseInt(x, 10));
  return ((ч[0] || 0) * 3600 + (ч[1] || 0) * 60 + (ч[2] || 0)) / 86400;
}
