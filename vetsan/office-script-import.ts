/**
 * Импорт акта мойки ЗПП из мобильного приложения.
 *
 * Работает в двух режимах:
 *   1. Из письма — Power Automate передаёт тело письма параметром «письмо».
 *      Врач ничего не открывает: заполнил акт → отправил письмо → книга заполнена.
 *   2. Вручную — параметр пуст, пакет берётся из ячейки A1 листа «Импорт»
 *      (кнопка «Копировать» в приложении → Ctrl+V → «Запустить»).
 *
 * Что заполняется:
 *   «Акт мойки»            — дата, 131 балл, описания, ответственные, отметка МДС
 *   «Хронометраж»          — начало и окончание мойки по дате
 *   «Динамика»             — итоговый балл по дате
 *   «Архив несоответствий» — строки нарушений в конец таблицы
 *   «Журнал несоответствий» не трогается: он собирается своими формулами.
 */

const ЛИСТ_АКТ = "Акт мойки";
const ЛИСТ_ХРОНО = "Хронометраж";
const ЛИСТ_ДИНАМИКА = "Динамика";
const ЛИСТ_АРХИВ = "Архив несоответствий";
const ЛИСТ_ИМПОРТ = "Импорт";
const ПЕРВАЯ_СТРОКА = 9;
const ПОСЛЕДНЯЯ_СТРОКА = 151;

/** отклонение: [строка, балл, описание, МДС, ответственный, срок] — хвост может быть обрезан */
type Отклонение = (string | number)[];

interface Пакет {
  v: number;
  act: string;   // номер акта
  d: string;     // дата, ГГГГ-ММ-ДД
  fio: string;   // ветеринарный врач
  t1: string;    // начало мойки
  t2: string;    // окончание мойки
  sc: number;    // итоговый средний балл
  rows: string;  // структура бланка: «9-52,54-58,…»
  x: Отклонение[];
}

function main(workbook: ExcelScript.Workbook, письмо?: string): string {
  // ---------- 1. Откуда взять пакет ----------
  let сырой = "";
  let изПисьма = false;
  if (письмо && письмо.trim() !== "") {
    сырой = извлечьПакет(письмо);
    изПисьма = true;
    if (сырой === "") throw new Error("В письме не найден пакет приложения — проверьте, что тело письма не пустое.");
  } else {
    let импорт = workbook.getWorksheet(ЛИСТ_ИМПОРТ);
    if (!импорт) {
      импорт = workbook.addWorksheet(ЛИСТ_ИМПОРТ);
      импорт.getRange("A1").setValue("");
      const м = "Готово: создан лист «Импорт». Вставьте пакет из приложения в ячейку A1 и запустите скрипт снова.";
      console.log(м);
      return м;
    }
    сырой = извлечьПакет(String(импорт.getRange("A1").getValue() || ""));
    if (сырой === "") {
      const м = "Ячейка A1 листа «Импорт» пуста. Вставьте пакет из приложения в A1 и запустите скрипт снова.";
      console.log(м);
      return м;
    }
  }

  const пакет: Пакет = JSON.parse(сырой) as Пакет;
  if (пакет.v !== 2) {
    throw new Error("Пакет неизвестного формата (версия " + пакет.v + "). Обновите страницу приложения и сформируйте акт заново.");
  }
  const отклонения = пакет.x || [];
  const серийнаяДата = вДатуExcel(пакет.d);

  // ---------- 2. Сверка структуры бланка ДО любой записи ----------
  const акт = workbook.getWorksheet(ЛИСТ_АКТ);
  const таблица = акт.getRange(`A${ПЕРВАЯ_СТРОКА}:I${ПОСЛЕДНЯЯ_СТРОКА}`).getValues();
  const позиции: number[] = [];
  for (let i = 0; i < таблица.length; i++) {
    const номер = таблица[i][0];
    const наименование = таблица[i][1];
    // строка 53 («ВКО») тоже содержит число в A, но объединена в A53:D53 —
    // от записи в неё спасает проверка наименования в колонке B
    if (typeof номер === "number" && typeof наименование === "string" && наименование !== "") {
      позиции.push(ПЕРВАЯ_СТРОКА + i);
    }
  }
  const структура = диапазоны(позиции);
  if (структура !== пакет.rows) {
    throw new Error(
      "Бланк «Акт мойки» изменился — в книгу ничего не записано. " +
      "Ожидались строки " + пакет.rows + ", в книге " + структура + ". " +
      "Если строки добавляли или удаляли намеренно, обновите список позиций в приложении."
    );
  }

  const карта: { [строка: number]: Отклонение } = {};
  for (const о of отклонения) карта[о[0] as number] = о;

  // ---------- 3. Лист «Акт мойки» ----------
  акт.getRange("C4").setValue(серийнаяДата);
  for (const блок of блоки(позиции)) {
    const мдс: string[][] = [];
    const баллы: number[][] = [];
    const описания: string[][] = [];
    const ответственные: string[][] = [];
    for (let строка = блок[0]; строка <= блок[1]; строка++) {
      const о = карта[строка];
      мдс.push([о && о[3] ? "да" : ""]);
      баллы.push([о ? (о[1] as number) : 10]);
      описания.push([о && о[2] ? String(о[2]) : ""]);
      ответственные.push([о && о[4] ? String(о[4]) : ""]);
    }
    const адрес = (кол: string) => `${кол}${блок[0]}:${кол}${блок[1]}`;
    акт.getRange(адрес("C")).setValues(мдс);
    акт.getRange(адрес("D")).setValues(баллы);
    акт.getRange(адрес("F")).setValues(описания);
    акт.getRange(адрес("G")).setValues(ответственные);
  }

  // ---------- 4. Лист «Хронометраж» ----------
  const хроно = workbook.getWorksheet(ЛИСТ_ХРОНО);
  const строкаХроно = найтиИлиДобавить(хроно, серийнаяДата, 2);
  хроно.getRange(`B${строкаХроно}`).setValue("ЗПП");
  if (пакет.t1) хроно.getRange(`C${строкаХроно}`).setValue(вДолюСуток(пакет.t1));
  if (пакет.t2) хроно.getRange(`F${строкаХроно}`).setValue(вДолюСуток(пакет.t2));
  хроно.getRange(`J${строкаХроно}`).setValue(пакет.fio);

  // ---------- 5. Лист «Динамика» ----------
  const динамика = workbook.getWorksheet(ЛИСТ_ДИНАМИКА);
  const строкаДин = найтиИлиДобавить(динамика, серийнаяДата, 2);
  динамика.getRange(`B${строкаДин}`).setValue("ЗПП");
  динамика.getRange(`C${строкаДин}`).setValue(пакет.sc);

  // ---------- 6. Лист «Архив несоответствий» ----------
  // участок и наименование берём с листа акта, а не из пакета: в книге они точнее
  const нарушения = отклонения.filter(о => (о[1] as number) < 10);
  if (нарушения.length > 0) {
    const архив = workbook.getWorksheet(ЛИСТ_АРХИВ);
    const первая = перваяПустая(архив, 4);
    const строки = нарушения.map(о => {
      const i = (о[0] as number) - ПЕРВАЯ_СТРОКА;
      return [
        серийнаяДата,
        String(таблица[i][8] || ""),          // I — участок
        String(таблица[i][1] || ""),          // B — наименование
        о[2] ? String(о[2]) : "",             // описание
        о[1] as number,                       // балл
        о[4] ? String(о[4]) : "",             // ответственный
        о[5] ? вДатуExcel(String(о[5])) : "", // срок
        "Открыто",
        ""
      ];
    });
    архив.getRange(`A${первая}:I${первая + строки.length - 1}`).setValues(строки);
  }

  // ---------- 7. Убираем за собой ----------
  if (!изПисьма) {
    workbook.getWorksheet(ЛИСТ_ИМПОРТ).getRange("A1").clear(ExcelScript.ClearApplyTo.contents);
  }
  // строка возвращается в Power Automate — её можно отправить врачу ответным письмом
  const итог =
    `Акт ${пакет.act} от ${пакет.d} принят. ` +
    `Позиций: ${позиции.length}. Несоответствий: ${нарушения.length}. ` +
    `Итоговый балл: ${пакет.sc}. Врач: ${пакет.fio}.`;
  console.log(итог + (изПисьма ? " Источник: письмо." : " Источник: лист «Импорт»."));
  return итог;
}

/**
 * Достаёт пакет из произвольного текста: письмо приходит в HTML-обёртке,
 * а почтовые программы дробят длинную строку переносами.
 * Внутри пакета настоящих переносов нет — они экранированы, поэтому удаляем все.
 */
function извлечьПакет(текст: string): string {
  // Порядок важен: переносы снимаются ПЕРВЫМИ. Почтовые программы рвут длинную
  // строку по ширине, и разрыв может попасть внутрь тега или «&quot;» —
  // тогда декодировать их уже поздно.
  let t = текст.replace(/=\r?\n/g, "");   // мягкий перенос quoted-printable
  t = t.replace(/[\r\n\t]/g, "");
  t = t.replace(/<[^>]*>/g, " ");
  t = t.replace(/&quot;/g, '"').replace(/&#34;/g, '"').replace(/&#039;/g, "'")
       .replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
       .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&");
  const от = t.indexOf("{");
  const до = t.lastIndexOf("}");
  return от >= 0 && до > от ? t.substring(от, до + 1) : "";
}

/** [9,10,11,13] → «9-11,13» */
function диапазоны(строки: number[]): string {
  if (строки.length === 0) return "";
  const части: string[] = [];
  let начало = строки[0], предыдущая = строки[0];
  for (let i = 1; i < строки.length; i++) {
    if (строки[i] !== предыдущая + 1) {
      части.push(начало === предыдущая ? `${начало}` : `${начало}-${предыдущая}`);
      начало = строки[i];
    }
    предыдущая = строки[i];
  }
  части.push(начало === предыдущая ? `${начало}` : `${начало}-${предыдущая}`);
  return части.join(",");
}

/** непрерывные диапазоны строк: [[9,52],[54,58],…] — запись блоками не задевает объединённые заголовки */
function блоки(строки: number[]): number[][] {
  const результат: number[][] = [];
  let начало = строки[0], предыдущая = строки[0];
  for (let i = 1; i < строки.length; i++) {
    if (строки[i] !== предыдущая + 1) {
      результат.push([начало, предыдущая]);
      начало = строки[i];
    }
    предыдущая = строки[i];
  }
  результат.push([начало, предыдущая]);
  return результат;
}

/** ищет дату в колонке A, при отсутствии — добавляет строку после последней заполненной */
function найтиИлиДобавить(лист: ExcelScript.Worksheet, дата: number, перваяСтрока: number): number {
  const колонка = лист.getRange(`A${перваяСтрока}:A${перваяСтрока + 999}`).getValues();
  let последняя = перваяСтрока - 1;
  for (let i = 0; i < колонка.length; i++) {
    const значение = колонка[i][0];
    if (значение === "" || значение === null) continue;
    последняя = перваяСтрока + i;
    if (typeof значение === "number" && Math.floor(значение) === дата) return последняя;
  }
  const новая = последняя + 1;
  лист.getRange(`A${новая}`).setValue(дата);
  return новая;
}

/** первая пустая строка по колонке A */
function перваяПустая(лист: ExcelScript.Worksheet, перваяСтрока: number): number {
  const колонка = лист.getRange(`A${перваяСтрока}:A${перваяСтрока + 4999}`).getValues();
  for (let i = колонка.length - 1; i >= 0; i--) {
    const значение = колонка[i][0];
    if (значение !== "" && значение !== null) return перваяСтрока + i + 1;
  }
  return перваяСтрока;
}

/** «2026-08-20» → серийный номер даты Excel */
function вДатуExcel(iso: string): number {
  const части = iso.split("-").map(ч => parseInt(ч, 10));
  const utc = Date.UTC(части[0], части[1] - 1, части[2]);
  return Math.round(utc / 86400000) + 25569;
}

/** «07:45:30» → доля суток (ячейка отформатирована как ч:мм) */
function вДолюСуток(время: string): number {
  const ч = время.split(":").map(x => parseInt(x, 10));
  return ((ч[0] || 0) * 3600 + (ч[1] || 0) * 60 + (ч[2] || 0)) / 86400;
}
